#!/usr/bin/env python3
"""Convert a PSF1/PSF2 console font into a C array (256 glyphs x 8x16)."""
import gzip, struct, sys

PSF1_MAGIC = b'\x36\x01'
PSF2_MAGIC = b'\x72\xb5\x4a\x86'

def load(path):
    data = open(path, 'rb').read()
    if path.endswith('.gz'):
        data = gzip.decompress(data)
    # PSF1: byte0 = 0x36, byte2 = mode, byte3 = glyph height
    if data[0] == 0x36 and 1 <= data[3] <= 32:
        mode, charsize = data[2], data[3]
        hdr = 4
        count = 512 if (mode & 0x01) else 256
        glyphs = data[hdr:hdr + count * charsize]
        if len(glyphs) < count * charsize:
            count = len(glyphs) // charsize
        return count, charsize, glyphs
    if data[:4] == PSF2_MAGIC:
        (magic, version, headersize, flags, length, charsize,
         height, width) = struct.unpack('<IIIIIIII', data[:32])
        glyphs = data[headersize:headersize + length * charsize]
        return length, charsize, glyphs, width, height
    raise SystemExit(f'not a PSF font: {path}')

def main():
    if len(sys.argv) != 3:
        raise SystemExit('usage: psf2c.py <font.psf[.gz]> <out.c>')
    src, out = sys.argv[1], sys.argv[2]
    if len(sys.argv) >= 3 and src.endswith(('.psf', '.psf.gz')):
        pass
    r = load(src)
    if len(r) == 3:
        count, charsize, glyphs = r
        width, height = 8, charsize
    else:
        count, charsize, glyphs, width, height = r
    if width != 8:
        raise SystemExit(f'need an 8px-wide font, got {width}px')
    rows = charsize // height if height else 1
    # normalize to 256 glyphs x `height` bytes
    gsz = charsize
    out_glyphs = []
    for i in range(256):
        if i < count:
            out_glyphs.append(glyphs[i * gsz:(i + 1) * gsz])
        else:
            out_glyphs.append(bytes(gsz))
    with open(out, 'w') as f:
        f.write('/* generated by tools/psf2c.py - do not edit */\n')
        f.write('#include <stdint.h>\n')
        f.write(f'const uint16_t aurora_font_w = {width};\n')
        f.write(f'const uint16_t aurora_font_h = {height};\n')
        f.write(f'const uint8_t aurora_font[{256 * gsz}] = {{\n')
        for i, g in enumerate(out_glyphs):
            hexes = ', '.join(f'0x{b:02x}' for b in g)
            f.write(f'    /* {i:02x} */ {hexes},\n')
        f.write('};\n')
    print(f'psf2c: {src} -> {out} (256 glyphs, {width}x{height})')

if __name__ == '__main__':
    main()
