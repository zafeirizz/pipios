#pragma once
#include <stdint.h>
#include <stddef.h>
#include "aurora.h"

/* ---------- framebuffer / pixel layer ---------- */

typedef struct {
    void     *fb;         /* framebuffer base (virtual address)    */
    uint32_t  width;      /* visible width  (pixels)               */
    uint32_t  height;     /* visible height (pixels)               */
    uint32_t  pitch;      /* bytes per scanline                     */
    uint32_t  bpp;        /* bits per pixel (16/24/32)             */
    uint32_t  bytes;      /* bytes per pixel                        */
    uint64_t  phys;       /* physical lfb address (for later ioctl)*/
} screen_t;

/* Initialise the screen layer from the boot info. Returns 0 on success. */
int  screen_init(boot_info_t *bi, screen_t *s);

/* Push a rectangular region of the offscreen desktop to the visible LFB. */
void screen_flush(const screen_t *s, uint32_t x, uint32_t y,
                  uint32_t w, uint32_t h, void *dst_fb);

/* Pixel primitives (operate on a linear buffer with given pitch/bpp). */
void fb_fill(void *fb, uint32_t w, uint32_t h, uint32_t pitch, uint32_t bpp,
             uint32_t color);
void fb_rect(void *fb, uint32_t w, uint32_t h, uint32_t pitch, uint32_t bpp,
             int32_t x, int32_t y, uint32_t w_, uint32_t h_, uint32_t color,
             int filled);
void fb_line(void *fb, uint32_t w, uint32_t h, uint32_t pitch, uint32_t bpp,
             int32_t x0, int32_t y0, int32_t x1, int32_t y1, uint32_t color);
void fb_pixel(void *fb, uint32_t pitch, uint32_t bpp,
              uint32_t x, uint32_t y, uint32_t color);

/* Color helpers. Colors are 0xRRGGBB packed (bpp conversion handles alpha). */
static inline uint32_t rgb(uint8_t r, uint8_t g, uint8_t b) {
    return ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
}
#define COLOR_BG     rgb(0x1f, 0x1f, 0x2e)   /* desktop wallpaper    */
#define COLOR_WIN    rgb(0x2a, 0x2a, 0x3d)   /* window fill          */
#define COLOR_TITLE  rgb(0x14, 0x14, 0x22)   /* titlebar fill        */
#define COLOR_FOCUS  rgb(0x3d, 0x6e, 0xff)   /* focused titlebar     */
#define COLOR_BORDER rgb(0x55, 0x55, 0x77)   /* window border        */
#define COLOR_TEXT   rgb(0xe0, 0xe0, 0xe8)   /* text                 */
#define COLOR_WHITE  0xffffff
#define COLOR_BLACK  0x000000

