extern const uint8_t  aurora_font[];      /* 256 glyphs, 1 byte/row  */
extern const uint16_t aurora_font_w;      /* glyph width  (px, 8)    */
extern const uint16_t aurora_font_h;      /* glyph height (px, 16)   */
#define FONT_GLYPHS  256u
#define FONT_ADVANCE ((uint32_t)aurora_font_w)

typedef struct { uint32_t width, height, advance, first; } font_info_t;

font_info_t font_info(void);
void       font_draw(void *fb, uint32_t w, uint32_t h, uint32_t pitch,
                     uint32_t bpp, int32_t x, int32_t y, uint32_t glyph,
                     uint32_t fg, uint32_t bg);
void       font_string(void *fb, uint32_t w, uint32_t h, uint32_t pitch,
                       uint32_t bpp, int32_t x, int32_t y, const char *s,
                       uint32_t fg, uint32_t bg);
int        font_measure(const char *s);

/* ---------- window geometry shared with apps ---------- */
#define TITLE_H 20        /* titlebar height (px)                  */
#define WIN_PAD 4         /* client content inset (px)             */
#define CLOSE_W 16        /* titlebar close box width              */
#define CLOSE_H 14        /* titlebar close box height             */

/* ---------- window compositor ---------- */

typedef struct window window_t;

/* Window procedure. 'ev' describes the mouse event; return 0. */
typedef void (*wp_t)(window_t *w, int32_t mx, int32_t my, int event);

enum {
    EV_MOVE = 1,     /* repaint request: draw client at (mx,my)  */
    EV_DOWN,         /* mouse button pressed inside the window   */
    EV_UP,           /* mouse button released                    */
    EV_KEY,          /* keyboard: mx carries the ASCII char      */
    EV_DESTROY,      /* window is being closed                   */
};

struct window {
    uint32_t x, y, w, h;   /* position/size on the desktop          */
    uint8_t  vis;           /* visible?                              */
    uint8_t  focused;       /* has keyboard/mouse focus              */
    uint8_t  drag;          /* user is dragging this window          */
    uint32_t drag_off_x, drag_off_y;
    char     title[64];    /* titlebar text (UTF-8/ASCII)           */
    void    *user;          /* app-owned state (terminal buf, ...)   */
    wp_t     proc;         /* window procedure (mouse/keyboard)     */
    window_t *next;        /* z-order list                          */
};

/* The compositor owns the offscreen desktop (double-buffering style). */
typedef struct {
    screen_t      screen;      /* visible framebuffer               */
    void         *buf;          /* offscreen composition buffer       */
    uint32_t      buf_pitch;    /* its pitch (same as screen)          */
    window_t     *windows;      /* z-ordered window list              */
    window_t     *focus;        /* currently focused window           */
    uint32_t      cursor_x, cursor_y;
    uint8_t       cursor_vis;
    uint32_t      cursor_hot_x, cursor_hot_y;
    const uint8_t *cursor_bits;
    uint32_t      cursor_w, cursor_h;
    wp_t          desktop_proc; /* draws/handles the bare desktop+taskbar */
    void         *user;          /* shell-owned state                      */
} compositor_t;

/* Set by gui_init; window procs use it to reach the desktop buffer. */
extern compositor_t *gui_active;

/* Initialise the compositor, allocate the offscreen buffer, paint the
 * wallpaper. Returns 0 on success. */
int  gui_init(compositor_t *c, boot_info_t *bi);
void gui_shutdown(compositor_t *c);

/* Push the offscreen buffer to the visible framebuffer (full screen). */
void gui_flush(compositor_t *c);

/* Full recompose: wallpaper, windows back-to-front, cursor, flush. */
void gui_compose(compositor_t *c);

/* Window lifecycle. All coordinates are relative to the desktop. */
window_t *gui_window_create(compositor_t *c, uint32_t x, uint32_t y,
                            uint32_t w, uint32_t h, const char *title,
                            wp_t proc);
void      gui_window_destroy(compositor_t *c, window_t *w);
void      gui_window_show(compositor_t *c, window_t *w);
void      gui_window_hide(compositor_t *c, window_t *w);
int       gui_window_move(compositor_t *c, window_t *w, uint32_t x, uint32_t y);
int       gui_window_resize(compositor_t *c, window_t *w, uint32_t w_, uint32_t h_);
void      gui_window_set_focus(compositor_t *c, window_t *w);
void      gui_window_bring_forward(compositor_t *c, window_t *w);

/* Paint a single window's contents into the offscreen buffer. Called by
 * the compositor each frame; subclasses may also call it directly. */
void gui_window_paint(compositor_t *c, window_t *w);

/* Run one iteration of the mouse-driven desktop:
 * - sample mouse x/y/buttons/events
 * - hit-test windows (topmost-first)
 * - dispatch EV_MOVE / EV_DOWN / EV_UP to the window under the cursor
 * - update cursor visibility
 * - re-compose and flush
 * Returns the number of mouse events consumed this frame. */
uint32_t gui_poll_mouse(compositor_t *c);

/* Forward a keyboard character to the focused window, if any. */
void gui_notify_key(compositor_t *c, int ch);

/* Draw the mouse cursor sprite into the offscreen buffer. */
void gui_draw_cursor(compositor_t *c);

/* A built-in arrow cursor bitmap is provided. */
const uint8_t *gui_arrow_cursor_bits(void);
uint32_t      gui_arrow_cursor_w(void);
uint32_t      gui_arrow_cursor_h(void);
uint32_t      gui_arrow_cursor_hot_x(void);
uint32_t      gui_arrow_cursor_hot_y(void);
